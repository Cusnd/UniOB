/* ============================================================================
 * Deterministic High-Density Linux Telemetry Series Generator
 * Produces realistic micro-spikes, asymmetric RX/TX packet bursts, and I/O jitter
 * ============================================================================ */
function createSeededRng(seed: number): () => number {
  let a = (seed * 2654435761) >>> 0;
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function buildSeries(params: {
  seed: number;
  baseCpu: number;
  cpuAmp: number;
  spikeAt?: number;
  spikeCpu?: number;
  stealBase?: number;
  memBasePct: number;
  swapBasePct: number;
  rxBase: number;
  txBase: number;
  iopsBase: number;
  tcpBase: number;
}): TelemetryPoint[] {
  const baseTs = 1763188800;
  const rng = createSeededRng(params.seed + 101);
  const points: TelemetryPoint[] = [];

  let rollingCpu = params.baseCpu;
  let rollingMem = params.memBasePct;
  let rollingRx = params.rxBase;
  let rollingTx = params.txBase;

  for (let i = 0; i < 60; i++) {
    const n1 = rng() - 0.5;
    const n2 = rng() - 0.5;
    const n3 = rng();

    // Mean-reverting random walk + realistic cron/worker micro-bursts
    const isMicroBurst = n3 > 0.84;
    const burstFactor = isMicroBurst ? 1.45 + rng() * 0.85 : 1.0;

    rollingCpu =
      rollingCpu * 0.58 +
      params.baseCpu * 0.42 +
      n1 * params.cpuAmp * 1.65 +
      (isMicroBurst ? params.cpuAmp * (0.7 + rng() * 0.9) : 0);

    let cpu = Math.max(1.4, Math.min(99.2, rollingCpu));

    if (params.spikeAt !== undefined && i >= params.spikeAt) {
      const dist = i - params.spikeAt;
      const target = (params.spikeCpu ?? 92) + n2 * 4.2;
      cpu = Math.min(99.4, cpu + (target - cpu) * Math.exp(-dist * 0.04));
    }

    const steal = Math.max(
      0,
      Number(
        (
          (params.stealBase ?? 0.2) +
          Math.abs(n2) * 1.4 +
          (n3 > 0.9 ? 1.2 : 0)
        ).toFixed(1),
      ),
    );
    const load1 = Number(((cpu / 100) * 2.15 + Math.abs(n1) * 0.22).toFixed(2));

    rollingMem =
      rollingMem * 0.78 +
      params.memBasePct * 0.22 +
      n2 * 2.4 +
      (i % 17 === 0 ? 1.8 : 0);
    const memPct = Number(Math.max(8, Math.min(97.5, rollingMem)).toFixed(1));

    const swapPct = Number(
      Math.max(
        0,
        Math.min(
          95,
          params.swapBasePct > 0
            ? params.swapBasePct + n1 * 2.2 + (isMicroBurst ? 1.1 : 0)
            : 0,
        ),
      ).toFixed(1),
    );

    // Distinct asymmetric RX vs TX bursts so dual-series curves separate crisply
    const rxSpike = rng() > 0.8 ? 1.55 + rng() * 0.95 : 0.76 + rng() * 0.48;
    const txSpike = rng() > 0.78 ? 1.48 + rng() * 1.05 : 0.72 + rng() * 0.52;
    rollingRx = rollingRx * 0.35 + params.rxBase * rxSpike * 0.65;
    rollingTx = rollingTx * 0.38 + params.txBase * txSpike * 0.62;

    const rxKbps = Math.max(18, Math.round(rollingRx * (isMicroBurst ? 1.28 : 1)));
    const txKbps = Math.max(14, Math.round(rollingTx));

    const ioBurst = rng() > 0.83 ? 2.4 + rng() * 1.5 : 0.55 + rng() * 0.8;
    const diskReadKbps = Math.max(
      4,
      Math.round(params.iopsBase * 4.4 * ioBurst * (0.4 + rng() * 0.9)),
    );
    const diskWriteKbps = Math.max(
      8,
      Math.round(params.iopsBase * 6.8 * burstFactor * (0.45 + rng() * 0.95)),
    );
    const iops = Math.max(
      3,
      Math.round(params.iopsBase * ioBurst * (0.75 + rng() * 0.5)),
    );
    const tcpEst = Math.max(
      4,
      Math.round(params.tcpBase + n1 * 26 + (isMicroBurst ? 18 : 0)),
    );

    const ts = baseTs + i * 2;
    const totalSec = 48 * 60 + i * 2;
    const mins = Math.floor(totalSec / 60) % 60;
    const secs = totalSec % 60;
    const hour = 14 + Math.floor(totalSec / 3600);
    const label = `${String(hour).padStart(2, "0")}:${String(mins).padStart(2, "0")}:${String(secs).padStart(2, "0")}`;

    points.push({
      ts,
      label,
      cpu: Number(cpu.toFixed(1)),
      steal,
      load1,
      memPct,
      swapPct,
      rxKbps,
      txKbps,
      diskReadKbps,
      diskWriteKbps,
      iops,
      tcpEst,
    });
  }
  return points;
}

